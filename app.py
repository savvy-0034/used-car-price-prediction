import streamlit as st
import pandas as pd
import joblib
import numpy as np

# Load trained Random Forest model
model = joblib.load("random_forest_model.pkl")

# Load training columns
X_train = pd.read_csv("X_train.csv")

# Page configuration
st.set_page_config(
    page_title="Used Car Price Predictor",
    page_icon="🚗",
    layout="centered"
)

# Title
st.title("🚗 Used Car Price Prediction System")
st.write("Enter the details of the car to predict its selling price.")

st.divider()

# Input fields
car_name = st.selectbox(
    "Car Name",
    sorted([
        col.replace("Car_Name_", "")
        for col in X_train.columns
        if col.startswith("Car_Name_")
    ])
)

year = st.number_input(
    "Year",
    min_value=2003,
    max_value=2026,
    value=2015,
    step=1
)

present_price = st.number_input(
    "Present Price (Lakhs)",
    min_value=0.0,
    value=6.5,
    step=0.1
)

kms_driven = st.number_input(
    "Kilometers Driven",
    min_value=0,
    value=30000,
    step=1000
)

fuel_type = st.selectbox(
    "Fuel Type",
    ["Petrol", "Diesel", "CNG"]
)

seller_type = st.selectbox(
    "Seller Type",
    ["Dealer", "Individual"]
)

transmission = st.selectbox(
    "Transmission",
    ["Manual", "Automatic"]
)

owner = st.number_input(
    "Number of Previous Owners",
    min_value=0,
    max_value=5,
    value=0,
    step=1
)

st.divider()

# Prediction button
if st.button("🔮 Predict Selling Price", use_container_width=True):

    # Create empty input with exact training columns
    input_data = pd.DataFrame(
        0,
        index=[0],
        columns=X_train.columns
    )

    # Numerical values
    input_data["Year"] = year
    input_data["Present_Price"] = present_price
    input_data["Kms_Driven"] = kms_driven
    input_data["Owner"] = owner

    # Car name
    car_column = "Car_Name_" + car_name
    if car_column in input_data.columns:
        input_data[car_column] = 1

    # Fuel type
    fuel_column = "Fuel_Type_" + fuel_type
    if fuel_column in input_data.columns:
        input_data[fuel_column] = 1

    # Seller type
    if seller_type == "Individual":
        if "Seller_Type_Individual" in input_data.columns:
            input_data["Seller_Type_Individual"] = 1

    # Transmission
    if transmission == "Manual":
        if "Transmission_Manual" in input_data.columns:
            input_data["Transmission_Manual"] = 1
            
    # Mileage Category (New Preprocessing Rule applied)
    if kms_driven > 100000:
        if "Mileage_Category_Very_High" in input_data.columns:
            input_data["Mileage_Category_Very_High"] = 1
    elif kms_driven > 60000:
        if "Mileage_Category_High" in input_data.columns:
            input_data["Mileage_Category_High"] = 1
    elif kms_driven > 30000:
        if "Mileage_Category_Medium" in input_data.columns:
            input_data["Mileage_Category_Medium"] = 1

    # Make prediction (This will output the Log value)
    prediction_log = model.predict(input_data)[0]
    
    # Reverse the Log Transformation (np.expm1) to get the actual price in Lakhs
    prediction = np.expm1(prediction_log)

    # Display result
    st.success("Prediction completed successfully!")

    st.subheader("💰 Predicted Selling Price")

    st.metric(
        label="Estimated Price",
        value=f"{prediction:.2f} Lakhs"
    )

    st.info(
        "This price is an estimated value generated by the Random Forest model."
    )